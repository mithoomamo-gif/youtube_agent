def adapt_channel_report(w1_report: dict) -> dict:
    production = w1_report.get("production") or {}
    channel = w1_report.get("channel") or {}
    quota_w1 = w1_report.get("quota") or {}
    buckets_w1 = quota_w1.get("buckets") or {}
    projects = []
    publishes = []
    for video in production.get("videos") or []:
        projects.append(
            {
                "project_id": video.get("project_id"),
                "topic": video.get("topic"),
                "status": video.get("status"),
                "created_at": video.get("created_at_ms"),
                "total_cost_micros": int(video.get("cost_micros") or 0),
            }
        )
        if video.get("publish_classification") not in (None, "not_published"):
            publishes.append(
                {
                    "project_id": video.get("project_id"),
                    "topic": video.get("topic"),
                    "youtube_video_id": video.get("youtube_video_id"),
                    "simulated": bool(video.get("simulated")),
                    "classification": video.get("publish_classification"),
                    "created_at": video.get("created_at_ms"),
                }
            )
    gates = (w1_report.get("gates") or {}).get("counts") or {}
    return {
        "scope": "channel",
        "kind": "receipt",
        "engine": "app.reporting",
        "engine_report_id": w1_report.get("report_id"),
        "channel": {
            "id": w1_report.get("channel_id"),
            "title": channel.get("title"),
        },
        "period": w1_report.get("period") or {},
        "projects": projects,
        "publishes": publishes,
        "costs": _adapt_costs(w1_report.get("costs") or {}),
        "quota": {
            "buckets": {
                name: int((bucket or {}).get("used") or 0)
                for name, bucket in buckets_w1.items()
            },
            "limits": {
                name: (bucket or {}).get("limit")
                for name, bucket in buckets_w1.items()
            },
            "total_units": int(quota_w1.get("total_units") or 0),
            "scope": "google_project",
        },
        "gates": gates,
    }


def render_channel_receipt(data: dict) -> tuple[str, str]:
    period = data["period"]
    start_ms, end_ms = period.get("start_ms"), period.get("end_ms")
    title = (
        f"Channel receipt — {data['channel'].get('title')}"
        f" — {_iso(start_ms)[:10]} to {_iso(end_ms)[:10]}"
    )
    lines = [
        f"# {title}",
        "",
        f"Window: {_iso(start_ms)} → {_iso(end_ms)}",
        "",
        "## Videos produced",
        "",
    ]
    if data["projects"]:
        for p in data["projects"]:
            lines.append(
                f"- {p.get('topic')} — status {p.get('status')},"
                f" cost {_usd(p.get('total_cost_micros'))} (`{p['project_id']}`)"
            )
    else:
        lines.append("No videos were produced in this window.")
    lines += ["", "## Publishing", ""]
    if data["publishes"]:
        for pub in data["publishes"]:
            label = (
                "SIMULATED (fake provider — not live on YouTube)"
                if pub["simulated"]
                else f"publish record ({pub.get('classification')})"
            )
            lines.append(
                f"- {pub.get('topic')} — {label}: `{pub.get('youtube_video_id')}`"
            )
    else:
        lines.append("Nothing was published in this window.")
    lines += [
        "",
        "## Costs (api_usage ledger actuals)",
        "",
        f"Total: **{_usd(data['costs']['total_cost_micros'])}**"
        f" across {data['costs']['total_calls']} provider calls.",
        "",
        "## YouTube quota used (shared Google project)",
        "",
    ]
    buckets = data["quota"]["buckets"]
    lines.append(
        f"Uploads {buckets.get('uploads', 0)} · Search {buckets.get('search', 0)}"
        f" · Shared {buckets.get('shared', 0)} units."
    )
    if data["gates"]:
        lines += ["", "## Gate decisions", ""]
        for gate, counts in sorted(data["gates"].items()):
            rendered = ", ".join(
                f"{count} {label}" for label, count in sorted(counts.items())
            )
            lines.append(f"- {gate}: {rendered}")
    return title, "\n".join(lines) + "\n"
