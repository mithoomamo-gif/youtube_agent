def adapt_video_report(w1_report: dict, *, agent_runs: list[dict]) -> dict:
    video = w1_report.get("video") or {}
    channel = w1_report.get("channel") or {}
    costs = _adapt_costs(w1_report.get("costs") or {})
    publish = _adapt_publish(w1_report.get("publish") or {})
    return {
        "scope": "video",
        "kind": "receipt",
        "engine": "app.reporting",
        "engine_report_id": w1_report.get("report_id"),
        "channel": {
            "id": w1_report.get("channel_id"),
            "title": channel.get("title"),
        },
        "period": w1_report.get("period") or {},
        "video": {
            "project_id": video.get("project_id") or w1_report.get("project_id"),
            "topic": video.get("topic"),
            "status": video.get("status"),
            "current_phase": video.get("current_phase"),
            "created_at": video.get("created_at_ms"),
            "published_at": publish.get("published_at"),
            "youtube_video_id": video.get("youtube_video_id"),
            "project_total_cost_micros": costs["project_ledger_micros"],
            "error_summary": video.get("error_summary"),
        },
        "gates": _adapt_gates(w1_report.get("gates") or {}),
        "publish": publish,
        "costs": costs,
        "agent_runs": agent_runs,
    }


def render_video_receipt(data: dict) -> tuple[str, str]:
    video = data["video"]
    title = f"Video receipt — {video.get('topic') or video['project_id']}"
    lines = [
        f"# {title}",
        "",
        f"Channel: {data['channel'].get('title')} (`{data['channel']['id']}`)",
        f"Project: `{video['project_id']}` · Status: {video.get('status')}"
        f" · Phase: {video.get('current_phase') or '—'}",
        f"Created: {_iso(video.get('created_at'))}",
        "",
        "## Publish state",
        "",
    ]
    publish = data["publish"]
    if publish["state"] == "not_published":
        lines.append("Not published — no publish record exists for this video.")
    elif publish.get("simulated"):
        lines.append(
            f"**Simulated (fake provider)** — {publish['label']}."
            f" Simulated video id: `{publish.get('youtube_video_id')}`,"
            f" privacy: {publish.get('privacy_status')}."
        )
    else:
        lines.append(
            f"Publish record: `{publish.get('youtube_video_id')}`"
            f" ({publish.get('video_url') or 'no URL recorded'}),"
            f" privacy: {publish.get('privacy_status')},"
            f" classification: {publish.get('classification')}."
        )
    lines += ["", "## Gates", ""]
    if data["gates"]:
        for gate, value in sorted(data["gates"].items()):
            lines.append(f"- {gate}: {value if isinstance(value, str) else 'recorded'}")
    else:
        lines.append("No gate decisions recorded for this project.")
    lines += ["", "## Costs (api_usage ledger actuals)", ""]
    costs = data["costs"]
    if costs["providers"]:
        lines.append("| Provider | Calls | Tokens in | Tokens out | Cost |")
        lines.append("|---|---|---|---|---|")
        for row in costs["providers"]:
            lines.append(
                f"| {row['provider']} | {row['calls']} | {row['tokens_in']}"
                f" | {row['tokens_out']} | {_usd(row['cost_micros'])} |"
            )
        lines.append(f"\nLedger total: **{_usd(costs['total_cost_micros'])}**"
                     f" across {costs['total_calls']} calls.")
    else:
        lines.append("No provider usage recorded for this video in the period.")
    lines.append(
        f"Project cumulative cost (projects ledger):"
        f" **{_usd(video.get('project_total_cost_micros'))}**."
    )
    lines += ["", "## Agent runs", ""]
    if data["agent_runs"]:
        lines.append("| Agent | Status | Model | Cost |")
        lines.append("|---|---|---|---|")
        for run in data["agent_runs"]:
            lines.append(
                f"| {run.get('agent_key')} | {run.get('status')}"
                f" | {run.get('model') or '—'} | {_usd(run.get('cost_micros'))} |"
            )
    else:
        lines.append("No agent runs recorded for this project.")
    if video.get("error_summary"):
        lines += ["", "## Errors", "", str(video["error_summary"])]
    return title, "\n".join(lines) + "\n"


