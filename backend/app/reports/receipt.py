"""Receipt presentation layer — W1 engine output in the W2 shape.

Receipts are GENERATED by W1's engine (:mod:`app.reporting`,
ledgers-only, persisted there in ``generated_reports``).  This
module adapts the engine's report document to the W2 HTTP contract
shape (the shape ``app.routers.reports`` has always served and the
Round 5 reconciliation audit asserts) and renders its Markdown.
The adapted artefact is stored by :mod:`app.reports.service` in the
``reports`` table alongside the weekly digests, so list/fetch serve
one consistent shape for every kind.

No figure is created here: every number is either copied from the
engine document or read from the same ledgers the engine reads
(agent-run rows for the per-video receipt).  Publish honesty is
inherited from the engine's classification — simulated
(fake-provider) publishes are labelled simulated, never live.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Optional

from app.reports import facts

_STATE_BY_CLASSIFICATION = {
    "simulated": "simulated_fake_provider",
    "published": "published_recorded",
    "unknown": "record_present_unconfirmed",
    "not_published": "not_published",
}

_SIMULATED_LABEL = "Simulated upload via the fake provider — NOT live on YouTube"


def _iso(ms: Optional[int]) -> str:
    if not ms:
        return "—"
    return datetime.fromtimestamp(int(ms) / 1000, tz=timezone.utc).strftime(
        "%Y-%m-%d %H:%M UTC"
    )


def _usd(micros: Any) -> str:
    return f"${int(micros or 0) / 1_000_000:.4f}"


def _adapt_costs(w1_costs: dict) -> dict:
    providers = []
    for row in w1_costs.get("by_provider") or []:
        providers.append(
            {
                "provider": row.get("provider"),
                "calls": int(row.get("calls") or 0),
                "cost_micros": int(row.get("cost_micros") or 0),
                "tokens_in": int(row.get("tokens_in") or 0),
                "tokens_out": int(row.get("tokens_out") or 0),
                "characters": int(row.get("characters") or 0),
                "images": int(row.get("images") or 0),
                "units": int(row.get("units") or 0),
            }
        )
    return {
        "providers": providers,
        "total_cost_micros": int(w1_costs.get("api_usage_micros") or 0),
        "total_calls": int(w1_costs.get("api_usage_calls") or 0),
        "project_ledger_micros": int(w1_costs.get("project_ledger_micros") or 0),
        "agent_runs_micros": int(w1_costs.get("agent_runs_micros") or 0),
    }


def _adapt_publish(w1_publish: dict) -> dict:
    classification = w1_publish.get("classification") or "not_published"
    simulated = bool(w1_publish.get("simulated"))
    return {
        "state": _STATE_BY_CLASSIFICATION.get(classification, "not_published"),
        "classification": classification,
        "simulated": simulated,
        "label": _SIMULATED_LABEL if simulated else w1_publish.get("label"),
        "engine_label": w1_publish.get("label"),
        "youtube_video_id": w1_publish.get("youtube_video_id"),
        "video_url": w1_publish.get("video_url"),
        "privacy_status": w1_publish.get("privacy_status"),
        "published_at": w1_publish.get("published_at_ms"),
    }


def _adapt_gates(w1_gates: dict) -> dict:
    adapted: dict[str, Any] = {}
    for key, value in (w1_gates or {}).items():
        if key == "counts":
            continue
        if isinstance(value, dict) and value.get("outcome") is not None:
            adapted[key] = value["outcome"]
        else:
            adapted[key] = value
    return adapted


