"""Report service — the shared service-layer contract + storage.

Contract (shared with the sibling report-engine work, W1):

* ``generate_report(scope, channel_id, video_id=None, period=None,
  kind='receipt')`` → stored artefact dict with ``data`` (JSON-able
  dict) and ``markdown``.
* ``list_reports(channel_id=None, scope=None, kind=None, limit=100)``
  → artefact summaries, newest first.
* ``get_report(report_id, channel_id=None)`` → full artefact or
  ``None``.  Passing a ``channel_id`` that does not own the report
  also yields ``None`` — the HTTP layer answers 404 either way, so
  existence never leaks across channels.

WIRING (W1 landed during this task): receipts are GENERATED by
W1's real engine, :mod:`app.reporting.service`
(``generate_video_report`` / ``generate_channel_report`` — the
engine also persists its own canonical copy in
``generated_reports``).  This module adapts the engine document to
the W2 contract shape via :mod:`app.reports.receipt`, renders the
W2 Markdown, and stores the adapted artefact in this module's own
``reports`` table — the store the HTTP layer lists/fetches, for
receipts and digests alike.  The weekly digest
(``kind='weekly_digest'``) is the one variant W1 deliberately does
not own; it is built by :mod:`app.reports.digest` from the same
ledgers.

Isolation: W1's engine builds a report for any project id it is
handed, so the channel-ownership checks live HERE — a video receipt
is only generated after the project is proven to belong to the
requested channel, and fetches compare the stored row's channel
against the requested one.

``period`` is ``{'start_ms': int, 'end_ms': int}`` (epoch ms).
Defaults: digest → the trailing 7 days ending now; receipts → the
engine's own default (the video's lifetime / the channel's full
history) unless an explicit period is supplied.
"""

from __future__ import annotations

import json
import time
import uuid
from typing import Any, Optional

from app import db as db_module
from app.errors import ApiError
from app.reports import digest as digest_module
from app.reports import facts, receipt as receipt_module
from app.reports.schema import ensure_reports_schema

__all__ = ["generate_report", "list_reports", "get_report"]


def _now_ms() -> int:
    return int(time.time() * 1000)


def _new_conn():
    return db_module.get_connection()


def _close(conn) -> None:
    try:
        conn.close()
    except Exception:
        pass


def _not_found(what: str, ident: Any) -> ApiError:
    return ApiError(404, f"{what}_not_found", f"{what} {ident} was not found")


def _period_bounds(period: Optional[dict]) -> tuple[Optional[int], Optional[int]]:
    """(start_ms, end_ms) from a contract period dict; Nones if absent."""
    if not period:
        return None, None
    start = period.get("start_ms", period.get("start"))
    end = period.get("end_ms", period.get("end"))
    start_ms = int(start) if start is not None else None
    end_ms = int(end) if end is not None else None
    if start_ms is not None and end_ms is not None and end_ms <= start_ms:
        raise ApiError(422, "invalid_period", "period end must be after its start")
    return start_ms, end_ms


def _row_artefact(row: dict, *, full: bool) -> dict:
    artefact = {
        "id": row["id"],
        "scope": row["scope"],
        "kind": row["kind"],
        "channel_id": row["channel_id"],
        "project_id": row.get("project_id"),
        "period": {
            "start_ms": row["period_start_ms"],
            "end_ms": row["period_end_ms"],
        },
        "period_start_ms": row["period_start_ms"],
        "period_end_ms": row["period_end_ms"],
        "title": row["title"],
        "created_at": row["created_at"],
    }
    if full:
        artefact["data"] = facts.parse_json(row.get("data_json"), {}) or {}
        artefact["markdown"] = row.get("markdown") or ""
    return artefact


def _store(
    conn,
    *,
    scope: str,
    kind: str,
    channel_id: str,
    project_id: Optional[str],
    period: dict,
    title: str,
    data: dict,
    markdown: str,
) -> dict:
    ensure_reports_schema(conn)
    report_id = uuid.uuid4().hex
    created_at = _now_ms()
    conn.execute(
        "INSERT INTO reports (id, scope, kind, channel_id, project_id,"
        " period_start_ms, period_end_ms, title, data_json, markdown,"
        " created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
        (
            report_id,
            scope,
            kind,
            channel_id,
            project_id,
            period.get("start_ms"),
            period.get("end_ms"),
            title,
            json.dumps(data),
            markdown,
            created_at,
        ),
    )
    conn.commit()
    row = dict(
        conn.execute(
            "SELECT * FROM reports WHERE id = ?", (report_id,)
        ).fetchone()
    )
    return _row_artefact(row, full=True)


