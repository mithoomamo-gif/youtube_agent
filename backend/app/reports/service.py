def generate_report(
    scope: str,
    channel_id: str,
    video_id: Optional[str] = None,
    period: Optional[dict] = None,
    *,
    kind: str = "receipt",
    conn=None,
) -> dict:
    """Generate a report from the ledgers and store the artefact."""
    if scope not in ("video", "channel"):
        raise ApiError(422, "invalid_scope", f"unknown report scope {scope!r}")
    if kind not in ("receipt", "weekly_digest"):
        raise ApiError(422, "invalid_kind", f"unknown report kind {kind!r}")
    if kind == "weekly_digest" and scope != "channel":
        raise ApiError(
            422, "invalid_kind", "weekly_digest requires channel scope"
        )
    own_conn = conn is None
    conn = conn or _new_conn()
    try:
        channel = facts.channel_row(conn, channel_id)
        if channel is None:
            raise _not_found("channel", channel_id)
        project = None
        if scope == "video":
            if not video_id:
                raise ApiError(
                    422, "video_required", "video scope requires a video_id"
                )
            # Ownership pre-check: W1's engine builds for any project
            # id, so the channel scope is enforced here (404, never a
            # cross-channel build).
            project = facts.find_project_for_video(conn, channel_id, video_id)
            if project is None:
                raise _not_found("video", video_id)
        start_ms, end_ms = _period_bounds(period)

        if kind == "weekly_digest":
            return _generate_digest(conn, channel, start_ms, end_ms)
        return _generate_receipt(
            conn, scope, channel, project, start_ms, end_ms
        )
    finally:
        if own_conn:
            _close(conn)


def _generate_receipt(
    conn,
    scope: str,
    channel: dict,
    project: Optional[dict],
    start_ms: Optional[int],
    end_ms: Optional[int],
) -> dict:
    """Receipt via W1's engine, adapted + stored in the W2 shape."""
    from app.reporting import service as w1_service

    try:
        if scope == "video":
            w1_report = w1_service.generate_video_report(
                conn,
                project["id"],
                period_start_ms=start_ms,
                period_end_ms=end_ms,
            )
            data = receipt_module.adapt_video_report(
                w1_report,
                agent_runs=facts.agent_runs_for_project(conn, project["id"]),
            )
            title, markdown = receipt_module.render_video_receipt(data)
        else:
            w1_report = w1_service.generate_channel_report(
                conn,
                channel["id"],
                period_start_ms=start_ms,
                period_end_ms=end_ms,
            )
            data = receipt_module.adapt_channel_report(w1_report)
            title, markdown = receipt_module.render_channel_receipt(data)
    except w1_service.ReportNotFoundError:
        raise _not_found(
            "video" if scope == "video" else "channel",
            project["id"] if project else channel["id"],
        ) from None
    period = w1_report.get("period") or {}
    return _store(
        conn,
        scope=scope,
        kind="receipt",
        channel_id=channel["id"],
        project_id=project["id"] if project else None,
        period={
            "start_ms": period.get("start_ms")
            if period.get("start_ms") is not None
            else start_ms,
            "end_ms": period.get("end_ms")
            if period.get("end_ms") is not None
            else end_ms,
        },
        title=title,
        data=data,
        markdown=markdown,
    )


def _generate_digest(
    conn,
    channel: dict,
    start_ms: Optional[int],
    end_ms: Optional[int],
) -> dict:
    now = _now_ms()
    resolved = {
        "start_ms": start_ms if start_ms is not None else now - facts.WEEK_MS,
        "end_ms": end_ms if end_ms is not None else now,
    }
    data = digest_module.build_digest_data(conn, channel, resolved)
    title, markdown = digest_module.render_digest(data)
    return _store(
        conn,
        scope="channel",
        kind="weekly_digest",
        channel_id=channel["id"],
        project_id=None,
        period=resolved,
        title=title,
        data=data,
        markdown=markdown,
    )


def list_reports(
    channel_id: Optional[str] = None,
    *,
    scope: Optional[str] = None,
    kind: Optional[str] = None,
    limit: int = 100,
    conn=None,
) -> list[dict]:
    """Stored report summaries, newest first, honouring the filters."""
    own_conn = conn is None
    conn = conn or _new_conn()
    try:
        ensure_reports_schema(conn)
        clauses: list[str] = []
        params: list[Any] = []
        if channel_id is not None:
            clauses.append("channel_id = ?")
            params.append(channel_id)
        if scope is not None:
            clauses.append("scope = ?")
            params.append(scope)
        if kind is not None:
            clauses.append("kind = ?")
            params.append(kind)
        where = f" WHERE {' AND '.join(clauses)}" if clauses else ""
        rows = [
            dict(r)
            for r in conn.execute(
                f"SELECT * FROM reports{where} ORDER BY created_at DESC"
                " LIMIT ?",
                (*params, max(1, min(int(limit), 500))),
            ).fetchall()
        ]
        return [_row_artefact(row, full=False) for row in rows]
    finally:
        if own_conn:
            _close(conn)


def get_report(
    report_id: str,
    *,
    channel_id: Optional[str] = None,
    conn=None,
) -> Optional[dict]:
    """One full artefact, or None — including when ``channel_id``
    names a different channel than the report's owner."""
    own_conn = conn is None
    conn = conn or _new_conn()
    try:
        ensure_reports_schema(conn)
        row = conn.execute(
            "SELECT * FROM reports WHERE id = ?", (report_id,)
        ).fetchone()
        if row is None:
            return None
        row = dict(row)
        if channel_id is not None and row["channel_id"] != channel_id:
            return None
        return _row_artefact(row, full=True)
    finally:
        if own_conn:
            _close(conn)
