"""Digest store table — runtime DDL + lazy schema creation.

Round 5 (Agent 31, Reporting).  Receipts are GENERATED by W1's
engine (:mod:`app.reporting`, which keeps its canonical copy in
``generated_reports``); this ``reports`` table is the W2 HTTP
store: it holds the adapted receipt artefacts the API serves
(``kind='receipt'``) and the one variant W2 builds itself — the
**weekly channel digest** (``kind='weekly_digest'``).  Each row
keeps BOTH representations (``data_json`` — the structured facts
the report was rendered from — and ``markdown``) so a fetch never
re-derives numbers and can never drift from what was generated.

The lazy-ensure pattern mirrors :mod:`app.style_lab.schema` (and
``app.routers.approvals`` / ``app.execution.budget_reservations``):
the table is created on first use, so digests work on databases
that have not run migrations.  Parity (Round 5 closure): migration
``0010_reports`` now carries this exact DDL (and the
``generated_reports`` DDL of :mod:`app.reporting.schema`), added
once revision numbering was coordinated; the lazy DDL below is
kept identical with the migration.

Conventions (section 15): TEXT uuid4 primary keys, INTEGER Unix
epoch-millisecond timestamps.  ``channel_id`` is the owner scope —
REFERENCES channels (id) ON DELETE RESTRICT — and every read path in
:mod:`app.reports.service` is filtered by it, so a report stored
under channel A is never visible under channel B.  ``project_id``
is set for per-video receipts (scope='video') and NULL for
channel-scope reports.
"""

from __future__ import annotations

__all__ = [
    "REPORTS_TABLE",
    "REPORTS_DDL",
    "INDEX_STATEMENTS",
    "ensure_reports_schema",
]

REPORTS_TABLE = "reports"

REPORTS_DDL = """
CREATE TABLE IF NOT EXISTS reports (
    id              TEXT PRIMARY KEY,
    scope           TEXT NOT NULL
                    CHECK (scope IN ('video', 'channel')),
    kind            TEXT NOT NULL
                    CHECK (kind IN ('receipt', 'weekly_digest')),
    channel_id      TEXT NOT NULL
                    REFERENCES channels (id) ON DELETE RESTRICT,
    project_id      TEXT NULL
                    REFERENCES projects (id) ON DELETE RESTRICT,
    period_start_ms INTEGER NOT NULL,
    period_end_ms   INTEGER NOT NULL,
    title           TEXT NOT NULL,
    data_json       TEXT NOT NULL,
    markdown        TEXT NOT NULL,
    created_at      INTEGER NOT NULL
)
"""

INDEX_STATEMENTS: list[str] = [
    """
    CREATE INDEX IF NOT EXISTS idx_reports_channel_created
    ON reports (channel_id, created_at DESC)
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_reports_project
    ON reports (project_id, created_at DESC)
    """,
]


def ensure_reports_schema(conn) -> None:
    """Create the ``reports`` table + indexes if absent (idempotent)."""
    conn.execute(REPORTS_DDL)
    for statement in INDEX_STATEMENTS:
        conn.execute(statement)
